/** Deterministic, accent-free URL slug — kept in sync with apps/api/src/traffic-sign/traffic-sign.service.ts. */
export function slugify(input: string): string {
  return input
    .normalize('NFD')
    .replace(/[̀-ͯ]/g, '')
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '');
}
